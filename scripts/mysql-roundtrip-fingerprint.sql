-- Logical schema fingerprint for one selected MySQL 8 database.
-- SHOW CREATE / mysqldump can differ textually after a valid restore (for
-- example an explicitly recorded CHARACTER SET on an inherited collation),
-- so compare normalized INFORMATION_SCHEMA properties instead. Data bytes are
-- compared independently using ordered, data-only mysqldump output.
SELECT 'DATABASE', DEFAULT_CHARACTER_SET_NAME, DEFAULT_COLLATION_NAME
FROM information_schema.SCHEMATA WHERE SCHEMA_NAME=DATABASE();

SELECT 'TABLE', TABLE_NAME, TABLE_TYPE, COALESCE(ENGINE,''), COALESCE(ROW_FORMAT,''),
       COALESCE(TABLE_COLLATION,''), COALESCE(CREATE_OPTIONS,''), COALESCE(TABLE_COMMENT,'')
FROM information_schema.TABLES WHERE TABLE_SCHEMA=DATABASE() ORDER BY BINARY TABLE_NAME;

SELECT 'COLUMN', TABLE_NAME, ORDINAL_POSITION, COLUMN_NAME, COLUMN_TYPE, IS_NULLABLE,
       IF(COLUMN_DEFAULT IS NULL,'NULL',CONCAT('VALUE:',HEX(COLUMN_DEFAULT))),
       COALESCE(CHARACTER_SET_NAME,''), COALESCE(COLLATION_NAME,''), EXTRA,
       COALESCE(GENERATION_EXPRESSION,''), COLUMN_COMMENT
FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE()
ORDER BY BINARY TABLE_NAME, ORDINAL_POSITION;

SELECT 'INDEX', TABLE_NAME, INDEX_NAME, NON_UNIQUE, SEQ_IN_INDEX, COALESCE(COLUMN_NAME,''),
       COALESCE(`COLLATION`,''), COALESCE(SUB_PART,''), INDEX_TYPE, IS_VISIBLE, COALESCE(EXPRESSION,'')
FROM information_schema.STATISTICS WHERE TABLE_SCHEMA=DATABASE()
ORDER BY BINARY TABLE_NAME, BINARY INDEX_NAME, SEQ_IN_INDEX;

SELECT 'CONSTRAINT', c.TABLE_NAME, c.CONSTRAINT_NAME, c.CONSTRAINT_TYPE, c.ENFORCED,
       COALESCE(ch.CHECK_CLAUSE,'')
FROM information_schema.TABLE_CONSTRAINTS c
LEFT JOIN information_schema.CHECK_CONSTRAINTS ch
  ON ch.CONSTRAINT_SCHEMA=c.CONSTRAINT_SCHEMA AND ch.CONSTRAINT_NAME=c.CONSTRAINT_NAME
WHERE c.TABLE_SCHEMA=DATABASE()
ORDER BY BINARY c.TABLE_NAME, BINARY c.CONSTRAINT_NAME;

SELECT 'KEY', TABLE_NAME, CONSTRAINT_NAME, ORDINAL_POSITION, COLUMN_NAME,
       COALESCE(POSITION_IN_UNIQUE_CONSTRAINT,''), COALESCE(REFERENCED_TABLE_NAME,''),
       COALESCE(REFERENCED_COLUMN_NAME,'')
FROM information_schema.KEY_COLUMN_USAGE WHERE TABLE_SCHEMA=DATABASE()
ORDER BY BINARY TABLE_NAME, BINARY CONSTRAINT_NAME, ORDINAL_POSITION;

SELECT 'REFERENCE', TABLE_NAME, CONSTRAINT_NAME, UPDATE_RULE, DELETE_RULE
FROM information_schema.REFERENTIAL_CONSTRAINTS WHERE CONSTRAINT_SCHEMA=DATABASE()
ORDER BY BINARY TABLE_NAME, BINARY CONSTRAINT_NAME;

SELECT 'VIEW', TABLE_NAME, VIEW_DEFINITION, CHECK_OPTION, IS_UPDATABLE, DEFINER, SECURITY_TYPE
FROM information_schema.VIEWS WHERE TABLE_SCHEMA=DATABASE() ORDER BY BINARY TABLE_NAME;

SELECT 'TRIGGER', TRIGGER_NAME, EVENT_MANIPULATION, EVENT_OBJECT_TABLE, ACTION_TIMING,
       ACTION_ORDER, ACTION_STATEMENT, DEFINER, SQL_MODE
FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA=DATABASE() ORDER BY BINARY TRIGGER_NAME;

SELECT 'ROUTINE', ROUTINE_NAME, ROUTINE_TYPE, COALESCE(DTD_IDENTIFIER,''),
       COALESCE(ROUTINE_DEFINITION,''), SECURITY_TYPE, IS_DETERMINISTIC,
       SQL_DATA_ACCESS, DEFINER, SQL_MODE
FROM information_schema.ROUTINES WHERE ROUTINE_SCHEMA=DATABASE() ORDER BY BINARY ROUTINE_NAME;

SELECT 'EVENT', EVENT_NAME, DEFINER, TIME_ZONE, EVENT_TYPE, COALESCE(EXECUTE_AT,''),
       COALESCE(INTERVAL_VALUE,''), COALESCE(INTERVAL_FIELD,''), COALESCE(STARTS,''),
       COALESCE(ENDS,''), STATUS, ON_COMPLETION, EVENT_DEFINITION, SQL_MODE
FROM information_schema.EVENTS WHERE EVENT_SCHEMA=DATABASE() ORDER BY BINARY EVENT_NAME;
