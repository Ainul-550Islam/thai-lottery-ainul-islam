<?php

declare(strict_types=1);

namespace Tests\Feature\LotteryGames;

use App\DTOs\LotteryGames\DigitBetSelection;
use App\Exceptions\LotteryGameException;
use App\Models\Bet;
use App\Models\GameBetAttribution;
use App\Services\LotteryGames\GameBetPlacementService;
use App\Services\LotteryGames\LiabilityExposureService;
use Tests\Support\LotteryGames\GameLaneTestCase;

/**
 * One idempotency key, one bet — even when the request arrives twice.
 *
 * WHY THIS IS A SEPARATE SUITE FROM PLACEMENT
 * Idempotency is the only thing standing between a flaky mobile network and a player
 * paying twice, and it is invisible in a happy-path test because the first call and the
 * hundredth look identical. So the failures it prevents are tested one at a time:
 *
 *   DOUBLE SPEND      the same key must not debit the wallet twice. Batch 1's purchase
 *                     path already replays on the key; the assertion here proves the
 *                     digit lane actually reaches that replay rather than bypassing it.
 *
 *   DOUBLE LIABILITY  this is the batch-2 specific one, and the reason this file exists.
 *                     The exposure counter has no memory of an idempotency key: reserve()
 *                     is a deliberately dumb increment. A replay that re-reserved would
 *                     leave the operator carrying twice the obligation it believes it has
 *                     on one number - and it would never be noticed, because the money and
 *                     the bet count are both correct. The replay path therefore returns the
 *                     ORIGINAL attribution before any reservation happens.
 *
 *   DOUBLE ATTRIBUTION  one bet must have exactly one attribution row. A second row would
 *                     make the cancellation release ambiguous about which amount to give
 *                     back.
 *
 *   KEY REUSE         the same key for a DIFFERENT bet is refused, not replayed and not
 *                     silently placed. "Replay" would drop the new bet; "place" would mean
 *                     one key produced two bets, which is the property the key denies.
 *
 *   KEY SCOPE         keys are generated by clients, so two players can collide by
 *                     accident. A collision is not a replay: scoping the lookup by user is
 *                     what stops one player receiving another player's receipt.
 */
final class GameBetIdempotencyTest extends GameLaneTestCase
{
    private function placement(): GameBetPlacementService
    {
        return app(GameBetPlacementService::class);
    }

    private function exposure(): LiabilityExposureService
    {
        return app(LiabilityExposureService::class);
    }

    /**
     * @return array{draw: \App\Models\Draw, user: \App\Models\User, wallet: \App\Models\Wallet}
     */
    private function ready(): array
    {
        ['draw' => $draw] = $this->openLane('lane_game');
        $player = $this->player('1000.00');

        $this->limitFor($draw, '3d_direct', '123');
        $this->limitFor($draw, '3d_direct', '456');

        return ['draw' => $draw, ...$player];
    }

    // =========================================================================
    // The replay
    // =========================================================================

    public function test_the_same_key_returns_the_same_bet_without_spending_again(): void
    {
        ['draw' => $draw, 'user' => $user, 'wallet' => $wallet] = $this->ready();
        $key = $this->key('replay');

        $first = $this->placement()->place(
            (int) $user->getKey(),
            new DigitBetSelection('lane_game', '3d_direct', '123', '10.00'),
            (int) $draw->getKey(),
            $key,
        );

        $second = $this->placement()->place(
            (int) $user->getKey(),
            new DigitBetSelection('lane_game', '3d_direct', '123', '10.00'),
            (int) $draw->getKey(),
            $key,
        );

        // Same bet, and the second answer says so rather than pretending to be new.
        $this->assertSame($first['bet_id'], $second['bet_id']);
        $this->assertSame($first['attribution_id'], $second['attribution_id']);
        $this->assertSame('accepted', $first['status']);
        $this->assertSame('replayed', $second['status']);

        // And the money moved exactly once.
        $this->assertSame('990.00', $wallet->fresh()->balance);
        $this->assertSame(1, Bet::query()->count());
    }

    public function test_a_replay_does_not_reserve_the_liability_a_second_time(): void
    {
        ['draw' => $draw, 'user' => $user] = $this->ready();
        $key = $this->key('replay-liability');

        $this->placement()->place(
            (int) $user->getKey(),
            new DigitBetSelection('lane_game', '3d_direct', '123', '10.00'),
            (int) $draw->getKey(),
            $key,
        );

        // Five retries: exactly what a client with a flaky connection does.
        for ($attempt = 0; $attempt < 5; $attempt++) {
            $this->placement()->place(
                (int) $user->getKey(),
                new DigitBetSelection('lane_game', '3d_direct', '123', '10.00'),
                (int) $draw->getKey(),
                $key,
            );
        }

        $this->assertSame(
            '9000.00',
            $this->exposure()->exposureFor($draw->getKey(), 'lane_game', '123', '3d_direct'),
            'the reserved liability is the one bet, not six',
        );

        $row = $this->exposure()->row($draw->getKey(), 'lane_game', '123', '3d_direct');
        $this->assertSame(1, (int) $row->version, 'the counter was incremented once');
    }

    public function test_a_replay_creates_no_second_attribution(): void
    {
        ['draw' => $draw, 'user' => $user] = $this->ready();
        $key = $this->key('replay-attribution');

        $this->placement()->place(
            (int) $user->getKey(),
            new DigitBetSelection('lane_game', '3d_direct', '123', '10.00'),
            (int) $draw->getKey(),
            $key,
        );

        $this->placement()->place(
            (int) $user->getKey(),
            new DigitBetSelection('lane_game', '3d_direct', '123', '10.00'),
            (int) $draw->getKey(),
            $key,
        );

        $this->assertSame(1, GameBetAttribution::query()->count());
    }

    public function test_a_replay_returns_the_frozen_payout_even_if_the_multiplier_changed_since(): void
    {
        ['draw' => $draw, 'user' => $user] = $this->ready();
        $key = $this->key('replay-frozen');

        $first = $this->placement()->place(
            (int) $user->getKey(),
            new DigitBetSelection('lane_game', '3d_direct', '123', '10.00'),
            (int) $draw->getKey(),
            $key,
        );

        $this->assertSame('9000.00', $first['potential_payout']);

        // An operator cuts the multiplier after the bet was taken. The bet is already
        // priced and reserved; a replay must not re-price it.
        $this->declareGame('lane_game', $this->laneGameConfig('lane_game', [
            'bet_types' => [
                '3d_direct' => [
                    'selection_digits' => 3,
                    'match_mode' => 'exact',
                    'payout_multiplier' => '450',
                    'market_key' => '3d_direct',
                ],
                '2d_bottom' => [
                    'selection_digits' => 2,
                    'match_mode' => 'suffix',
                    'payout_multiplier' => '90',
                    'market_key' => '2d_bottom',
                ],
            ],
        ]));

        $second = $this->placement()->place(
            (int) $user->getKey(),
            new DigitBetSelection('lane_game', '3d_direct', '123', '10.00'),
            (int) $draw->getKey(),
            $key,
        );

        $this->assertSame('replayed', $second['status']);
        $this->assertSame('9000.00', $second['potential_payout'], 'the frozen amount, not the current 4,500.00');
        $this->assertSame('9000.00', $this->exposure()->exposureFor($draw->getKey(), 'lane_game', '123', '3d_direct'));
    }

    public function test_a_replay_is_answered_even_after_the_draw_has_closed(): void
    {
        ['draw' => $draw, 'user' => $user] = $this->ready();
        $key = $this->key('replay-closed');

        $this->placement()->place(
            (int) $user->getKey(),
            new DigitBetSelection('lane_game', '3d_direct', '123', '10.00'),
            (int) $draw->getKey(),
            $key,
        );

        // The draw closes between the original request and its retry. A retry of an
        // ALREADY ACCEPTED bet must still be answered; a NEW bet would be refused.
        $draw->forceFill(['betting_close_at' => now()->subMinute()])->save();

        $replayed = $this->placement()->place(
            (int) $user->getKey(),
            new DigitBetSelection('lane_game', '3d_direct', '123', '10.00'),
            (int) $draw->getKey(),
            $key,
        );

        $this->assertSame('replayed', $replayed['status']);

        try {
            $this->placement()->place(
                (int) $user->getKey(),
                new DigitBetSelection('lane_game', '3d_direct', '456', '10.00'),
                (int) $draw->getKey(),
                $this->key('fresh-after-close'),
            );
            $this->fail('a new bet after the window closed must still be refused');
        } catch (LotteryGameException $e) {
            $this->assertSame('game_not_sellable', $e->errorCode());
        }
    }

    // =========================================================================
    // Key reuse and key scope
    // =========================================================================

    public function test_the_same_key_for_a_different_bet_is_refused(): void
    {
        ['draw' => $draw, 'user' => $user, 'wallet' => $wallet] = $this->ready();
        $key = $this->key('reuse');

        $this->placement()->place(
            (int) $user->getKey(),
            new DigitBetSelection('lane_game', '3d_direct', '123', '10.00'),
            (int) $draw->getKey(),
            $key,
        );

        try {
            $this->placement()->place(
                (int) $user->getKey(),
                new DigitBetSelection('lane_game', '3d_direct', '456', '10.00'),
                (int) $draw->getKey(),
                $key,
            );
            $this->fail('a key reused for a different bet must be refused');
        } catch (LotteryGameException $e) {
            $this->assertSame('game_not_sellable', $e->errorCode());
            $this->assertSame('game_idempotency_key_reused', $e->context()['reason']);
            $this->assertSame('123', $e->context()['original']['number']);
            $this->assertSame('456', $e->context()['requested']['number']);
        }

        // Neither a second bet nor a second debit.
        $this->assertSame(1, Bet::query()->count());
        $this->assertSame('990.00', $wallet->fresh()->balance);
        $this->assertSame('0.00', $this->exposure()->exposureFor($draw->getKey(), 'lane_game', '456', '3d_direct'));
    }

    public function test_the_same_key_used_by_two_different_players_is_not_a_replay(): void
    {
        ['draw' => $draw, 'user' => $first] = $this->ready();
        $secondPlayer = $this->player('1000.00');
        $sharedKey = $this->key('shared-key');

        $firstReceipt = $this->placement()->place(
            (int) $first->getKey(),
            new DigitBetSelection('lane_game', '3d_direct', '123', '10.00'),
            (int) $draw->getKey(),
            $sharedKey,
        );

        $secondReceipt = $this->placement()->place(
            (int) $secondPlayer['user']->getKey(),
            new DigitBetSelection('lane_game', '3d_direct', '123', '10.00'),
            (int) $draw->getKey(),
            $sharedKey,
        );

        $this->assertNotSame($firstReceipt['bet_id'], $secondReceipt['bet_id'], 'the second player got their OWN bet');
        $this->assertSame('accepted', $secondReceipt['status']);
        $this->assertSame(2, Bet::query()->count());
        $this->assertSame('990.00', $secondPlayer['wallet']->fresh()->balance);
        $this->assertSame('18000.00', $this->exposure()->exposureFor($draw->getKey(), 'lane_game', '123', '3d_direct'));
    }

    public function test_a_blank_key_is_refused_before_anything_is_read(): void
    {
        ['draw' => $draw, 'user' => $user, 'wallet' => $wallet] = $this->ready();

        try {
            $this->placement()->place(
                (int) $user->getKey(),
                new DigitBetSelection('lane_game', '3d_direct', '123', '10.00'),
                (int) $draw->getKey(),
                "\t",
            );
            $this->fail('a blank key must be refused');
        } catch (LotteryGameException $e) {
            $this->assertSame('game_not_sellable', $e->errorCode());
            $this->assertSame('game_idempotency_key_required', $e->context()['reason']);
        }

        $this->assertSame(0, Bet::query()->count());
        $this->assertSame('1000.00', $wallet->fresh()->balance);
    }

    public function test_two_different_keys_are_two_bets(): void
    {
        ['draw' => $draw, 'user' => $user, 'wallet' => $wallet] = $this->ready();

        $this->placement()->place(
            (int) $user->getKey(),
            new DigitBetSelection('lane_game', '3d_direct', '123', '10.00'),
            (int) $draw->getKey(),
            $this->key('two-a'),
        );

        $second = $this->placement()->place(
            (int) $user->getKey(),
            new DigitBetSelection('lane_game', '3d_direct', '123', '10.00'),
            (int) $draw->getKey(),
            $this->key('two-b'),
        );

        $this->assertSame('accepted', $second['status']);
        $this->assertSame(2, Bet::query()->count());
        $this->assertSame('980.00', $wallet->fresh()->balance);
        $this->assertSame('18000.00', $this->exposure()->exposureFor($draw->getKey(), 'lane_game', '123', '3d_direct'));
    }
}
