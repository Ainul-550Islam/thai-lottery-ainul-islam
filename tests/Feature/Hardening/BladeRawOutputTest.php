<?php

declare(strict_types=1);

namespace Tests\Feature\Hardening;

use Tests\TestCase;

/**
 * Raw Blade output: the short list of places `{!! !!}` is allowed, and why.
 *
 * ============================================================================
 * THE HAZARD
 * ============================================================================
 * `{{ $x }}` escapes. `{!! $x !!}` does not. On this product the values that
 * reach a view include a member's display name, a support message they typed, a
 * KYC rejection note written by an operator, a bank's slip description and the
 * body of a marketing article. Any one of those, echoed raw, is stored XSS in a
 * session that can move money.
 *
 * Laravel's escaper is not optional for user data, so the rule is: raw output is
 * allowed only where the string is NOT user data — JSON that must stay JSON, and
 * pagination markup that is generated by the paginator itself.
 *
 * Each allowed file carries its reason below. A new `{!! !!}` in a file that is
 * not on the list fails this suite, and the failure message names the expression
 * so the fix is obvious.
 */
final class BladeRawOutputTest extends TestCase
{
    /**
     * View paths allowed to contain a raw echo, each with the reason.
     *
     * @var array<string, string>
     */
    private const ALLOWED = [
        'resources/views/components/seo/json-ld.blade.php' =>
            'JSON-LD must be valid JSON: it is json_encode()d from an array this application builds, inside a typed script tag with a CSP nonce.',
        'resources/views/results/index.blade.php' =>
            'The JSON payload handed to the results page script is json_encode()d, not printed from user input.',
        'resources/views/blog/show.blade.php' =>
            'Article bodies are sanitised ON WRITE by the article service before storage; the comment above the echo states it.',
        'resources/views/vendor/livewire/tailwind.blade.php' =>
            'Vendor paginator markup: translator output owned by this application.',
        'resources/views/vendor/pagination/tailwind.blade.php' =>
            'Vendor paginator markup: translator output owned by this application.',
        'resources/views/vendor/livewire/simple-tailwind.blade.php' =>
            'Vendor paginator markup: translator output owned by this application.',
    ];

    /**
     * @return array<string, list<string>> view path => matching raw expressions
     */
    private function rawEchoes(): array
    {
        $found = [];

        foreach ($this->bladeFiles() as $relative => $source) {
            // The window is generous because a JSON payload spans many lines; a
            // 120-character limit silently stopped matching those and made the
            // allow-list test report a file as clean when it was not.
            if (preg_match_all('/\{!!(.{0,8000}?)!!\}/s', $source, $matches) === 0) {
                continue;
            }

            $found[$relative] = array_map(
                static fn (string $expression): string => trim(preg_replace('/\s+/', ' ', $expression) ?? ''),
                $matches[1],
            );
        }

        return $found;
    }

    /**
     * @return array<string, string> relative path => contents
     */
    private function bladeFiles(): array
    {
        $files = [];
        $root = resource_path('views');

        $iterator = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($root, \FilesystemIterator::SKIP_DOTS));

        foreach ($iterator as $file) {
            if (! $file->isFile() || ! str_ends_with($file->getFilename(), '.blade.php')) {
                continue;
            }

            $relative = str_replace('\\', '/', str_replace(base_path().'/', '', $file->getPathname()));

            // Comments first. A docblock that SAYS "{!! !!} is not used here" is
            // not a raw echo, and treating it as one produced a phantom empty
            // expression that no assertion could ever satisfy.
            $source = (string) file_get_contents($file->getPathname());
            $source = (string) preg_replace('/\{\{--.*?--\}\}/s', '', $source);
            $source = (string) preg_replace('/<!--.*?-->/s', '', $source);

            $files[$relative] = $source;
        }

        ksort($files);

        return $files;
    }

    public function test_raw_echoes_appear_only_in_the_named_views(): void
    {
        $offenders = [];

        foreach (array_keys($this->rawEchoes()) as $relative) {
            if (! array_key_exists($relative, self::ALLOWED)) {
                $offenders[] = $relative;
            }
        }

        $this->assertSame(
            [],
            $offenders,
            "these views echo unescaped output and are not on the allow list:\n  - ".implode("\n  - ", $offenders),
        );
    }

    public function test_the_allow_list_does_not_rot(): void
    {
        $present = array_keys($this->rawEchoes());
        $stale = array_values(array_diff(array_keys(self::ALLOWED), $present));

        $this->assertSame(
            [],
            $stale,
            "these views are on the allow list but no longer contain a raw echo; remove the entry:\n  - "
            .implode("\n  - ", $stale),
        );
    }

    public function test_every_allowed_view_states_its_reason(): void
    {
        foreach (self::ALLOWED as $view => $reason) {
            $this->assertNotSame('', trim($reason), $view.' has no stated reason');
            $this->assertGreaterThan(20, strlen($reason), $view.' reason is too short to be a reason');
        }
    }

    public function test_no_unreviewed_view_echoes_a_request_or_session_value_raw(): void
    {
        // The narrowest, most useful rule of all: whatever else changes, a value
        // that came from the request, the session, a model or the auth user is
        // never printed unescaped.
        $patterns = [
            '/\{!!\s*\$request\b/',
            '/\{!!\s*session\s*\(/',
            '/\{!!\s*\$errors\b/',
            '/\{!!\s*auth\s*\(/',
            '/\{!!\s*\$user\b/',
            '/\{!!\s*\$article\b/',
            '/\{!!\s*\$message\b/',
            '/\{!!\s*\$reason\b/',
            '/\{!!\s*\$note\b/',
        ];

        $offenders = [];

        foreach ($this->bladeFiles() as $relative => $source) {
            // The allow list IS the reviewed set: every entry above carries a
            // reason and the allow-list test proves the list cannot grow quietly.
            // Files outside it must not echo a user-controlled value raw.
            if (array_key_exists($relative, self::ALLOWED)) {
                continue;
            }

            foreach ($patterns as $pattern) {
                if (preg_match($pattern, $source) === 1) {
                    $offenders[] = $relative.' matches '.$pattern;

                    break;
                }
            }
        }

        $this->assertSame([], $offenders, "a user-controlled value is echoed raw:\n  - ".implode("\n  - ", $offenders));
    }

    public function test_json_payloads_are_encoded_rather_than_interpolated(): void
    {
        foreach ($this->rawEchoes() as $relative => $expressions) {
            $reason = self::ALLOWED[$relative] ?? '';
            $sanitisedOnWrite = str_contains($reason, 'sanitised ON WRITE');

            foreach ($expressions as $expression) {
                if (str_contains($expression, 'json_encode')) {
                    continue;
                }

                // A sanitised-on-write body is the one reviewed exception: the
                // stored value passed an allow-list sanitiser before it was saved,
                // so re-escaping it would print HTML tags as text.
                if ($sanitisedOnWrite && preg_match('/^\$[\w>\-\[\]\'"]+$/', $expression) === 1) {
                    continue;
                }

                // Everything else must be translator output.
                $this->assertMatchesRegularExpression(
                    '/^__\(|^trans\(/',
                    $expression,
                    $relative.' echoes an expression that is neither JSON, a translation, nor a sanitised body: '.$expression,
                );
            }
        }
    }
}
