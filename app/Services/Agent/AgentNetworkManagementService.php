<?php

declare(strict_types=1);

namespace App\Services\Agent;

use App\Models\Agent;
use App\Models\AgentHierarchy;
use App\Models\CommissionLedger;
use App\Models\LotteryEntry;

/**
 * Class AgentNetworkManagementService
 *
 * Provides $O(1)$ subtree genealogy resolution, downline turnover aggregation,
 * and commission performance analytics for multi-tier agent structures.
 */
class AgentNetworkManagementService
{
    /**
     * Get entire downline subtree for an agent up to given depth.
     */
    public function getDownlineTree(string $agentId, int $maxDepth = 5): array
    {
        $descendants = AgentHierarchy::with(['descendant'])
            ->where('ancestor_id', $agentId)
            ->where('depth', '>', 0)
            ->where('depth', '<=', $maxDepth)
            ->orderBy('depth', 'asc')
            ->get();

        return $descendants->map(function ($node) {
            return [
                'agent_id' => $node->descendant_id,
                'agent_code' => $node->descendant->agent_code,
                'tier_level' => $node->descendant->tier_level,
                'depth_from_requester' => $node->depth,
                'direct_commission_rate' => $node->descendant->direct_commission_rate,
                'status' => $node->descendant->status,
            ];
        })->toArray();
    }

    /**
     * Calculate consolidated downline turnover and earned commissions.
     */
    public function getAgentPerformanceSummary(string $agentId, ?string $drawId = null): array
    {
        $descendantIds = AgentHierarchy::where('ancestor_id', $agentId)->pluck('descendant_id');

        // Total turnover generated by downline entries
        $turnoverQuery = LotteryEntry::whereIn('agent_id', $descendantIds);
        if ($drawId) {
            $turnoverQuery->where('draw_id', $drawId);
        }

        $totalTurnover = (string) ($turnoverQuery->sum('stake_amount') ?? '0.0000');
        $totalEntries = $turnoverQuery->count();

        // Total commissions accrued by this agent
        $commQuery = CommissionLedger::where('agent_id', $agentId)->where('status', 'POSTED');
        if ($drawId) {
            $commQuery->where('draw_id', $drawId);
        }

        $totalEarnedCommission = (string) ($commQuery->sum('commission_amount') ?? '0.0000');

        return [
            'agent_id' => $agentId,
            'total_downline_agents' => max(0, $descendantIds->count() - 1),
            'total_entries_count' => $totalEntries,
            'total_downline_turnover' => number_format((float) $totalTurnover, 4, '.', ''),
            'total_earned_commission' => number_format((float) $totalEarnedCommission, 4, '.', ''),
        ];
    }
}
